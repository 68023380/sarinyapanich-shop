require('dotenv').config();
const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const rateLimit = require('express-rate-limit');
const path = require('path');
const { healthCheck } = require('./db/postgres');
const authRoutes = require('./routes/auth.routes');
const productRoutes = require('./routes/products.routes');
const categoryRoutes = require('./routes/categories.routes');
const cartRoutes = require('./routes/cart.routes');
const orderRoutes = require('./routes/orders.routes');
const uploadRoutes = require('./routes/uploads.routes');

const app = express();
const port = Number(process.env.PORT || 3000);
const allowedOrigins = (process.env.CORS_ORIGIN || '').split(',').map(value=>value.trim()).filter(Boolean);
app.use(helmet({ crossOriginResourcePolicy: { policy:'cross-origin' } }));
app.use(cors({ origin:(origin,cb)=>!origin || allowedOrigins.length===0 || allowedOrigins.includes(origin) ? cb(null,true) : cb(new Error('Origin ไม่ได้รับอนุญาต')) }));
app.use(express.json({ limit:'1mb' }));
app.use(express.urlencoded({ extended:true }));
app.use('/uploads', express.static(path.resolve(process.env.UPLOAD_DIR || './uploads')));
app.use('/api/auth', rateLimit({ windowMs:15*60*1000, max:100, standardHeaders:true, legacyHeaders:false }), authRoutes);
app.use('/api/products', productRoutes);
app.use('/api/categories', categoryRoutes);
app.use('/api/cart', cartRoutes);
app.use('/api/orders', orderRoutes);
app.use('/api/uploads', uploadRoutes);
app.get('/api/health', async (req,res,next)=>{ try { const database = await healthCheck(); res.json({ ok:true, service:'sarinyapanich-backend', database:'postgresql', databaseTime:database.server_time, time:new Date().toISOString() }); } catch (error) { next(error); } });
app.use((req,res)=>res.status(404).json({ error:'ไม่พบเส้นทาง API' }));
app.use((err,req,res,next)=>{ console.error(err); if(err.message==='Origin ไม่ได้รับอนุญาต')return res.status(403).json({error:err.message}); res.status(500).json({error:'เกิดข้อผิดพลาดภายในเซิร์ฟเวอร์'}); });
app.listen(port, '0.0.0.0', ()=>console.log(`Sarinyapanich API running on http://localhost:${port}`));
